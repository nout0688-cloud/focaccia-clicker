export type CookieRewardType = 'diamonds' | 'frenzy' | 'ingredients' | 'focaccia';

export interface CookieReward {
  type: CookieRewardType;
  titleUk: string;
  titleRu: string;
  icon: string;
  descriptionUk: string;
  descriptionRu: string;
  diamonds?: number;
  frenzySeconds?: number;
  ingredients?: Record<string, number>;
  focaccia?: number;
}

export const COOKIE_COOLDOWN_MS = 5 * 60 * 1000; // 5 minutes free cooldown
export const COOKIE_INSTANT_DIAMOND_COST = 2; // 2 diamonds to crack instantly

export function getRandomFortune(): Fortune {
  const idx = Math.floor(Math.random() * FORTUNES.length);
  return FORTUNES[idx];
}

export function generateCookieReward(currentCps: number, clickPower: number): CookieReward {
  const roll = Math.random();

  // 1. 30% Chance: Jackpot Diamonds 💎 (5 - 25 diamonds)
  if (roll < 0.30) {
    const dia = 5 + Math.floor(Math.random() * 21); // 5 to 25
    return {
      type: 'diamonds',
      titleUk: 'Діамантовий Джекпот!',
      titleRu: 'Алмазный Джекпот!',
      icon: '💎',
      diamonds: dia,
      descriptionUk: `+${dia} Діамантів прямо до скарбниці!`,
      descriptionRu: `+${dia} Алмазов прямо в казну!`,
    };
  }

  // 2. 25% Chance: Golden Frenzy Rush 🔥 (20 seconds)
  if (roll < 0.55) {
    return {
      type: 'frenzy',
      titleUk: 'Золотий Екстаз Френзі!',
      titleRu: 'Золотой Экстаз Френзи!',
      icon: '🔥',
      frenzySeconds: 20,
      descriptionUk: '20 секунд бурхливого х6 Френзі-клікінгу!',
      descriptionRu: '20 секунд бурного х6 Френзи-кликинга!',
    };
  }

  // 3. 25% Chance: Rare Alchemy Ingredients ⚗️
  if (roll < 0.80) {
    const ingRoll = Math.random();
    let ings: Record<string, number>;
    let ingDescUk = '';
    let ingDescRu = '';
    let icon = '⚗️';

    if (ingRoll < 0.25) {
      ings = { truffle: 1 + (Math.random() < 0.3 ? 1 : 0) };
      icon = '🍄';
      ingDescUk = `+${ings.truffle} Золотий Трюфель`;
      ingDescRu = `+${ings.truffle} Золотой Трюфель`;
    } else if (ingRoll < 0.60) {
      ings = { star_yeast: 2 + Math.floor(Math.random() * 2) };
      icon = '🌾';
      ingDescUk = `+${ings.star_yeast} Зоряні Дріжджі`;
      ingDescRu = `+${ings.star_yeast} Звёздные Дрожжи`;
    } else if (ingRoll < 0.80) {
      ings = { volcano_olive: 2 + Math.floor(Math.random() * 2) };
      icon = '🫒';
      ingDescUk = `+${ings.volcano_olive} Вулканічні Оливки`;
      ingDescRu = `+${ings.volcano_olive} Вулканические Оливки`;
    } else {
      ings = { moon_honey: 3 + Math.floor(Math.random() * 2), mystic_basil: 3 };
      icon = '🍯';
      ingDescUk = `+${ings.moon_honey} Місячний Мед, +3 Базилік`;
      ingDescRu = `+${ings.moon_honey} Лунный Мёд, +3 Базилик`;
    }

    return {
      type: 'ingredients',
      titleUk: 'Алхімічний Скарб!',
      titleRu: 'Алхимическое Сокровище!',
      icon,
      ingredients: ings,
      descriptionUk: ingDescUk,
      descriptionRu: ingDescRu,
    };
  }

  // 4. 20% Chance: Baker's Focaccia Bounty Drop 🫓
  const base = Math.max(5000, currentCps * 600, clickPower * 250);
  const variance = 0.8 + Math.random() * 0.5; // 80% to 130%
  const amount = Math.floor(base * variance);

  return {
    type: 'focaccia',
    titleUk: 'Щедрий Кулінарний Куш!',
    titleRu: 'Щедрый Кулинарный Куш!',
    icon: '🫓',
    focaccia: amount,
    descriptionUk: `Величезна гора свіжої випічки!`,
    descriptionRu: `Огромная гора свежей выпечки!`,
  };
}
